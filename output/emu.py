def _banner(version, source):
    stamp = time.strftime("%d/%m/%Y %H:%M")
    return ("// supQ\n"
            "// generated by minh dumper (by minhlo123df) on %s\n"
            "// roblox %s - base: %s\n\n" % (stamp, version, source))


