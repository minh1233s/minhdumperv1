def render_emu_offsets(version, local_map):
    text = _EMU_TEMPLATE
    for marker, namespace, field, fallback in _EMU_MAP:
        text = text.replace(marker, _resolve(local_map, namespace, field, fallback))
    return _banner(version, "supQ Offsets.hpp") + text


def _read_source(filename):
    path = os.path.join(SUPQ_UPDATE_DIR, filename)
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            return handle.read()
    except OSError:
        return None


def _strip_legacy_banner(text):
    first_pragma = text.find("#pragma once")
    return text[first_pragma:] if first_pragma != -1 else text


def render_emu_fflags(version, local_map):
    source = _read_source("FFlags.hpp")
    if source is None:
        return None
    text = _strip_legacy_banner(source)
    pointer = _resolve(local_map, ("Hyperion",), "FLogDataBank", "0x8e1b0d0")
    text = re.sub(r"(namespace FFlagList\s*\{\s*inline constexpr uintptr_t Pointer = )0x[0-9a-fA-F]+",
                  r"\g<1>" + pointer, text, count=1)
    text = re.sub(r'(inline std::string ClientVersion = ")version-[0-9a-fA-F]+(";)',
                  r"\g<1>" + version + r"\g<2>", text, count=1)
    return _banner(version, "supQ FFlags.hpp (theo's list)") + text


def render_emu_verbatim(version, source_name, base_note):
    source = _read_source(source_name)
    if source is None:
        return None
    text = _strip_legacy_banner(source)
    return _banner(version, base_note) + text


def render_emu_set(version, local_map):
    outputs = {}
    outputs[EMU_OFFSETS] = render_emu_offsets(version, local_map)
    for filename, renderer in (
        (EMU_FFLAGS, render_emu_fflags(version, local_map)),
        (EMU_ENCRYPTIONS, render_emu_verbatim(version, "Encryptions.hpp", "supQ Encryptions.hpp")),
        (EMU_ENCRYPTIONS_HELPER, render_emu_verbatim(version, "EncryptionsHelper.hpp", "supQ EncryptionsHelper.hpp")),
        (EMU_SELF_TEST, render_emu_verbatim(version, "OffsetsSelfTest.hpp", "supQ OffsetsSelfTest.hpp")),
    ):
        if renderer is not None:
            outputs[filename] = renderer
    return outputs
